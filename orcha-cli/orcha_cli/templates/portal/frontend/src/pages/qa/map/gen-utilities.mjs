#!/usr/bin/env node
/**
 * Writes utilities.css: the utility classes the QA map, atlas, scenarios and sessions screens use
 * (Tailwind 4 run once, kept out of the portal's dependencies). Re-run after adding a class:
 *
 *   mkdir /tmp/tw && (cd /tmp/tw && npm init -y && npm i tailwindcss@4 @tailwindcss/cli@4)
 *   TAILWIND_DIR=/tmp/tw node src/pages/qa/map/gen-utilities.mjs     # from portal/frontend
 *
 * Each class is scoped to `.qa-port` with the specificity of one class, so it beats the portal's
 * element rules (a, h1…) and loses to a screen's own stylesheet loaded after it.
 */
import { execFileSync } from "node:child_process";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import postcss from "postcss";

const here = path.dirname(fileURLToPath(import.meta.url));
const tw = process.env.TAILWIND_DIR;
if (!tw) throw new Error("Set TAILWIND_DIR to a folder with tailwindcss@4 and @tailwindcss/cli@4 installed.");
const roots = ["map", "atlas", "scenarios", "sessions", "runs", "onboarding"].map((d) => path.join(here, "..", d));
const input = `
@layer theme, utilities;
@import "tailwindcss/theme.css" layer(theme);
@import "tailwindcss/utilities.css" layer(utilities);
${roots.map((r) => `@source "${r}/**/*.{ts,tsx}";`).join("\n")}
@custom-variant dark (&:where([data-theme="dark"], [data-theme="dark"] *));
@theme {
  --color-*: initial;
${["transparent:transparent", "current:currentColor"].map((c) => `  --color-${c.split(":")[0]}: ${c.split(":")[1]};`).join("\n")}
${["white", "black", "side", "window", "bg", "panel", "panel-2", "raised", "panel-border", "fg", "fg-2", "muted", "border", "border-strong", "hover", "selected", "control", "accent", "accent-fg", "accent-soft", "ring", "primary", "primary-hover", "primary-fg", "chart-1", "chart-2", "chart-3", "chart-4", "chart-5", "series-1", "series-2", "series-3", "series-4", "sev-blocker", "sev-major", "sev-minor", "sev-cosmetic", "sev-info", "danger", "success", "warning", "info", "progress", "neutral", "edge", "edge-active"].map((c) => `  --color-${c}: var(--qa-${c});`).join("\n")}
  --radius-xs: 3px; --radius-sm: 4px; --radius-md: 6px; --radius-lg: 8px; --radius-xl: 12px; --radius-panel: 10px;
  --shadow-sm: var(--qa-shadow-sm); --shadow-md: var(--qa-shadow-md); --shadow-panel: var(--qa-shadow-panel);
  --font-sans: var(--qa-font-sans); --font-mono: var(--qa-font-mono);
  --text-2xs: 10px; --text-2xs--line-height: 14px;
  --text-xs: 11px; --text-xs--line-height: 16px;
  --text-sm: 12px; --text-sm--line-height: 18px;
  --text-base: 13px; --text-base--line-height: 20px;
  --text-lg: 15px; --text-lg--line-height: 22px;
  --text-xl: 18px; --text-xl--line-height: 26px;
  --text-2xl: 22px; --text-2xl--line-height: 28px;
  --tracking-tight: -0.006em;
}
@utility tabular { font-variant-numeric: tabular-nums; }
`;
const entry = path.join(tw, "qa-input.css");
const output = path.join(tw, "qa-output.css");
fs.writeFileSync(entry, input);
execFileSync(path.join(tw, "node_modules/.bin/tailwindcss"), ["-i", entry, "-o", output, "--optimize"], { cwd: tw, stdio: "inherit" });

const root = postcss.parse(fs.readFileSync(output, "utf8"));
root.walkAtRules("layer", (at) => {
  if (!at.nodes) return at.remove();
  // The scale the utilities compute from (--spacing, --font-weight-*, --container-*…) stays, under
  // `.qa-port`; the colours and the rest that port.css maps to Orcha's tokens go.
  if (at.params === "theme") {
    at.walkDecls((d) => { if (d.value.includes("var(--qa-") || /^--(color|text|radius|shadow|font-(sans|mono)|tracking-tight)/.test(d.prop)) d.remove(); });
    at.walkRules((r) => { r.selector = ".qa-port"; });
  }
  at.replaceWith(at.nodes);
});
root.walkRules((rule) => {
  if (rule.parent?.type === "atrule" && /keyframes/.test(rule.parent.name)) return;
  if (rule.selector === ".qa-port" || rule.selector.startsWith(":root") || rule.selector.startsWith(":host") || rule.selector === "*" || rule.selector.startsWith("*,")) return;
  rule.selectors = rule.selectors.map((s) => `:where(.qa-port) ${s}`);
  // The portal's `.hidden` is `display: none !important`: a class that shows it again must say so too.
  if (rule.selector.includes("\\:")) rule.walkDecls("display", (d) => { d.important = true; });
});
root.walkDecls((d) => { d.value = d.value.replace(/var\(--qa-/g, "var(--"); });
const head = "/* GENERATED by gen-utilities.mjs: do not edit by hand. */\n";
fs.writeFileSync(path.join(here, "utilities.css"), head + root.toString() + "\n");
